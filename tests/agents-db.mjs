  await call(key2,'claim',{runId:failed[0].id});
  const stopped=await call(key2,'fail',{error:'No saved GitHub issues are available.'});
  assert.equal(stopped[0].status,'failed');
  assert.equal((await db.query('select count(*)::int n from memories where source_run_id=$1',[failed[0].id])).rows[0].n,0);
  console.log('PASS failure persistence without invented output');
  const key3='00000000-0000-4000-8000-000000000022';
  let invalid=await call(key3,'start',{goal:'Research market',steps:[{agentId:'research',objective:'Research market',actionType:'analyze_context',dependsOn:[]}]});
  await call(key3,'claim',{runId:invalid[0].id});
  await assert.rejects(call(key3,'finish',{runId:invalid[0].id,output:{...output,actions:[{...output.actions[0],actionType:'gmail.send_email'}]},usage:{}}));
  assert.equal((await db.query('select count(*)::int n from memories where source_run_id=$1',[invalid[0].id])).rows[0].n,0);
  assert.equal((await db.query('select status from ai_actions where agent_run_id=$1',[invalid[0].id])).rows[0].status,'executing');
