  assert.equal(runs[0].status,'waiting_approval');
  assert.ok(await call(key,'claim',{runId:runs[1].id}));
  runs=await call(key,'finish',{runId:runs[1].id,output:{...output,actions:[]},usage:{modelCalls:1}});
  assert.equal(runs[1].status,'completed');
  await assert.rejects(call(key,'finish',{runId:runs[1].id,output,usage:{}}));
  const action=(await db.query("select * from ai_actions where agent_run_id=$1 and action_type='create_task'",[runs[0].id])).rows[0];
  await db.exec(`set role authenticated; select set_config('request.jwt.claims','{"sub":"${owner}","role":"authenticated"}',false)`);
  await assert.rejects(db.query("update ai_actions set permission_level='AUTO' where id=$1",[action.id]));
  await assert.rejects(db.query("update ai_actions set agent_id='coding' where id=$1",[action.id]));
  await assert.rejects(db.query('delete from ai_actions where id=$1',[action.id]));
