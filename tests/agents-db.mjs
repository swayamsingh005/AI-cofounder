  const key='00000000-0000-4000-8000-000000000020';
  const plan={goal:'Research competitors and prepare a launch strategy',steps:[{agentId:'research',objective:'Research competitors',actionType:'analyze_context',dependsOn:[]},{agentId:'marketing',objective:'Prepare launch strategy',actionType:'analyze_context',dependsOn:[0]}]};
  await db.exec('set role service_role');
  let runs=await call(key,'start',plan); assert.equal(runs.length,2);
  const replay=await call(key,'start',plan); assert.equal(replay[0].id,runs[0].id);
  await assert.rejects(call(key,'start',{...plan,goal:'Different goal'}));
  await assert.rejects(call(key,'claim',{runId:runs[1].id}));
  assert.ok(await call(key,'claim',{runId:runs[0].id}));
  assert.equal(await call(key,'claim',{runId:runs[0].id}),null);
