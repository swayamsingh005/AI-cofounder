  const schema = ['schema.sql','v2-schema.sql','v3-company-os-schema.sql','v5-daily-brief-schema.sql','v6-next-best-action.sql'];
  for (const file of schema) await db.exec(fs.readFileSync(path.join('supabase',file),'utf8'));
