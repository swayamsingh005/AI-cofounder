  await assert.rejects(call(key,'claim',{runId:runs[0].id}));
  await assert.rejects(db.query('select execute_internal_action_v2($1,true)',[action.id]));
  await assert.rejects(db.query('select execute_internal_action($1,false)',[action.id]));
