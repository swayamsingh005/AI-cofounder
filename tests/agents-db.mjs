  assert.deepEqual(again,approved);
  assert.equal((await db.query('select status from agent_runs where id=$1',[runs[0].id])).rows[0].status,'completed');
  await assert.rejects(db.query("update memories set content='forged' where source_run_id=$1",[runs[0].id]));
  await assert.rejects(db.query("delete from activity_events where agent_run_id=$1",[runs[0].id]));
  await db.exec(`select set_config('request.jwt.claims','{"sub":"${other}","role":"authenticated"}',false)`);
  for (const table of ['agent_runs','ai_actions','memories','activity_events']) assert.equal((await db.query('select * from '+table+' where company_id=$1',[company])).rows.length,0);
  await assert.rejects(db.query('select execute_internal_action($1,true)',[action.id]));
  console.log('PASS workflow dependencies, replay protection, approvals, provenance and tenant isolation');
